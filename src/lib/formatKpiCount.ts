// KPI の通数表示用の丸め。
//
// 月間目標は営業日数で按分するため、累計目標も「本日残り」も小数になる。
// さらにアポ連動（kpi_daily_quota）の倍率が掛かるので端数が残り、
// 素の toLocaleString() だと「59.158通」のような読みにくい表示になる。
//
// 計算そのものは小数のまま扱う（色・ペース判定がずれるため）。
// 丸めるのは画面に出す瞬間だけ。

/**
 * 通数を整数にして表示用の文字列にする。基本は四捨五入。
 *
 * 0 より大きく 1 未満だけは「1」に切り上げる。
 * 「本日残り 0通」と出ているのに未達の色（赤）が付いたままになるのを避けるため。
 * 残りが 0 のときだけ「0」と出るようにしておく。
 */
export function kpiCount(n: number): string {
  if (n > 0 && n < 1) return '1'
  return Math.round(n).toLocaleString()
}
